// Embed ../page/*.js into src/snippets.js so the bundled CLI carries them. `--check` fails on drift.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const pageDir = join(here, "..", "..", "page");
const outFile = join(here, "..", "src", "snippets.js");
const map = {};
for (const f of readdirSync(pageDir).filter((f) => f.endsWith(".js")).sort()) map[f] = readFileSync(join(pageDir, f), "utf8");
const out = "// GENERATED by scripts/gen-snippets.mjs from ../page/*.js. Do not edit.\nexport const SNIPPETS = " + JSON.stringify(map, null, 2) + ";\n";
if (process.argv.includes("--check")) {
  const cur = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (cur !== out) { console.error("src/snippets.js is stale: run node scripts/gen-snippets.mjs"); process.exit(1); }
  console.log("snippets in sync");
} else { writeFileSync(outFile, out); console.log("wrote src/snippets.js (" + Object.keys(map).length + " snippets)"); }
